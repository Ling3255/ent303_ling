function initialLang() {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved === "zh" || saved === "en") return saved;
  return (navigator.language || "zh").toLowerCase().startsWith("zh") ? "zh" : "en";
}

// 给非 React 代码（api.js 的错误信息）用
let currentLang = initialLang();
export const getLang = () => currentLang;

export function translate(lang, key, params) {
  let s = dict[lang]?.[key] ?? dict.zh[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, v ?? "");
  return s;
}

const CJK = /[\u3400-\u9fff\uf900-\ufaff\u3000-\u303f\uff00-\uffef]/;
export const hasCjk = (s) => CJK.test(s || "");

// 后端的文字是 {zh, en}；英文界面下如果拿到的还是中文（旧数据或漏翻），宁可显示英文兜底也不显示中文。
// 只用于系统文字；用户输入、论文标题和原文引文不经过这里。
export function pickText(lang, value, fallback = "") {
  if (value == null) return "";
  const text = typeof value === "object" ? value[lang] ?? value.en ?? value.zh ?? "" : String(value);
  if (lang === "en" && hasCjk(text)) return fallback;
  return text;
}

const LangContext = createContext(null);

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(currentLang);
  const setLang = useCallback((l) => {
    currentLang = l;
    localStorage.setItem(LANG_KEY, l);
    setLangState(l);
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  }, [lang]);
  const value = useMemo(
    () => ({
      lang,
      setLang,
      t: (key, params) => translate(lang, key, params),
      tx: (v, fallback) => pickText(lang, v, fallback),
      locale: lang === "zh" ? "zh-CN" : "en-GB",
    }),
    [lang, setLang],
  );
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export const useI18n = () => useContext(LangContext);

export function LangToggle() {
  const { lang, setLang, t } = useI18n();
  return (
    <div className="lang-toggle" role="group" aria-label={t("lang.switch")} title={t("lang.switch")}>
      <button className={lang === "zh" ? "on" : ""} onClick={() => setLang("zh")} aria-pressed={lang === "zh"}>
        中
      </button>
      <button className={lang === "en" ? "on" : ""} onClick={() => setLang("en")} aria-pressed={lang === "en"}>
        EN
      </button>
    </div>
  );
}
